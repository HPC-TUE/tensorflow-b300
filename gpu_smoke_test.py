#!/usr/bin/env python3
"""GPU smoke test for the self-built TensorFlow wheel.

Checks, on the GPU the container is started on:
  1. the driver, CUDA libraries and ptxas are visible to TensorFlow,
  2. matmul and friends (cuBLAS, cuSolver, cuFFT, XLA) match a CPU reference,
  3. Keras layers match a CPU reference, and models train with and without XLA,
  4. the PTX generated by XLA is accepted by ptxas for this GPU's architecture,
     and neither LLVM, ptxas nor the driver complained about PTX while running.

Usage:
  /venv/bin/python /gpu_smoke_test.py               # exit 0 only if all pass
  /venv/bin/python /gpu_smoke_test.py --expect-arch sm_103   # B300, also fail on any other GPU
  /venv/bin/python /gpu_smoke_test.py --allow-cpu   # dry run, proves nothing about the GPU
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# Any of these in the TensorFlow log means PTX or the GPU runtime is not healthy,
# even if the op that triggered it fell back and returned a correct result.
BAD_LOG_PATTERNS = [
    r"is not a recognized processor",  # LLVM NVPTX backend does not know the GPU
    r"CUDA_ERROR_INVALID_PTX",
    r"CUDA_ERROR_UNSUPPORTED_PTX_VERSION",
    r"CUDA_ERROR_NO_BINARY_FOR_GPU",
    r"CUDA_ERROR_INVALID_SOURCE",
    r"ptxas exited with non-zero",
    r"[Cc]ouldn't (?:get|find) ptxas",
    r"Unknown opcode",
    r"Unsupported \.version",
    r"Cannot dlopen some GPU libraries",
    r"Failed call to cuInit",
    r"could not find cuda drivers",
]

results = []


def record(name, ok, detail=""):
    results.append((name, ok))
    status = "PASS" if ok else "FAIL"
    print(f"[{status}] {name}{': ' + str(detail) if detail else ''}", flush=True)
    return ok


def run_cmd(*cmd):
    return subprocess.run(cmd, capture_output=True, text=True, timeout=300)


############################## GPU workload (worker) ##############################


def worker(device):
    import numpy as np
    import tensorflow as tf
    import keras

    gpus = tf.config.list_physical_devices("GPU")
    for gpu in gpus:
        tf.config.experimental.set_memory_growth(gpu, True)

    build = tf.sysconfig.get_build_info()
    print(f"TensorFlow {tf.__version__}, Keras {keras.__version__}, numpy {np.__version__}")
    print(f"Built for CUDA {build.get('cuda_version')}, cuDNN {build.get('cudnn_version')}")
    record("wheel is a CUDA build", build.get("is_cuda_build", False))
    if device == "/GPU:0":
        record("TensorFlow sees a GPU", bool(gpus), gpus)
        if not gpus:
            return
        print(tf.config.experimental.get_device_details(gpus[0]))

    def check(name, fn):
        try:
            with tf.device("/CPU:0"):
                expected = [np.asarray(t) for t in tf.nest.flatten(fn())]
            with tf.device(device):
                actual = tf.nest.flatten(fn())
            on_device = all(device.strip("/").split(":")[0] in t.device for t in actual)
            worst = 0.0
            for a, e in zip(actual, expected):
                a = np.asarray(a)
                worst = max(worst, np.max(np.abs(a - e)) / max(np.max(np.abs(e)), 1e-12))
            # float32 gemm on the B300 is around 3e-4 from the CPU above size 16, see the README
            tol = 1e-12 if expected[0].dtype == np.float64 else 1e-3
            record(name, on_device and bool(worst <= tol),
                   f"device={actual[0].device.split('/')[-1]} rel_err={worst:.2e}")
        except Exception as e:
            record(name, False, f"{type(e).__name__}: {str(e)[:500]}")

    # Ops must really run on the GPU here, a silent CPU fallback has to be an error.
    tf.config.set_soft_device_placement(False)

    with tf.device(device):
        exact = tf.linalg.matmul(tf.constant([[1.0, 2.0], [3.0, 4.0]]),
                                 tf.constant([[5.0, 6.0], [7.0, 8.0]]))
    record("matmul known answer", np.array_equal(exact.numpy(), [[19, 22], [43, 50]]), exact.numpy().tolist())

    rng = np.random.default_rng(0)

    def rand(*shape, dtype=np.float32):
        return tf.constant(rng.standard_normal(shape).astype(dtype))

    a32, b32 = rand(1024, 512), rand(512, 2048)
    a64, b64 = rand(512, 512, dtype=np.float64), rand(512, 512, dtype=np.float64)
    batch_a, batch_b = rand(16, 64, 32), rand(16, 32, 8)
    cplx = tf.complex(rand(128, 128), rand(128, 128))
    spd = tf.constant((lambda m: m @ m.T + 256 * np.eye(256))(rng.standard_normal((256, 256)).astype(np.float64)))
    signal = tf.complex(rand(4096), tf.zeros(4096))
    values = rand(100000)

    check("cuBLAS matmul float32 non-square", lambda: tf.linalg.matmul(a32, b32))
    check("cuBLAS matmul float64", lambda: tf.linalg.matmul(a64, b64))
    check("cuBLAS matmul transpose", lambda: tf.linalg.matmul(a64, b64, transpose_a=True, transpose_b=True))
    check("cuBLAS matmul batched", lambda: tf.linalg.matmul(batch_a, batch_b))
    check("cuBLAS matmul complex64", lambda: tf.linalg.matmul(cplx, cplx))
    check("cholesky", lambda: tf.linalg.cholesky(spd))
    check("cuFFT fft", lambda: tf.signal.fft(signal))

    # jit_compile forces the path LLVM NVPTX -> PTX -> ptxas -> cubin. Each function is
    # one XLA module, so these all end up in the PTX dump checked by the parent process.
    xla_matmul = tf.function(lambda x, y: tf.linalg.matmul(x, y), jit_compile=True)
    xla_expr = tf.function(lambda x, y: tf.nn.relu(tf.linalg.matmul(x, y)) + tf.math.exp(-tf.abs(x @ y)),
                           jit_compile=True)
    xla_reduce = tf.function(lambda x: tf.reduce_sum(tf.math.sin(x) * tf.math.tanh(x), axis=0), jit_compile=True)
    xla_conv = tf.function(lambda x, k: tf.nn.conv2d(x, k, 1, "SAME"), jit_compile=True)
    xla_sort = tf.function(lambda x: tf.sort(x), jit_compile=True)  # may use the prebuilt cub sort kernel
    xla_topk = tf.function(lambda x: tf.math.top_k(x, k=16).values, jit_compile=True)
    images, kernel = rand(4, 32, 32, 3), rand(3, 3, 3, 8)

    check("XLA matmul float32", lambda: xla_matmul(a32, b32))
    check("XLA matmul float64", lambda: xla_matmul(a64, b64))
    check("XLA matmul + elementwise fusion", lambda: xla_expr(a64, b64))
    check("XLA reduce fusion", lambda: xla_reduce(a32))
    check("XLA conv2d", lambda: xla_conv(images, kernel))
    check("XLA sort", lambda: xla_sort(values))
    check("XLA top_k", lambda: xla_topk(values))

    tf.config.set_soft_device_placement(True)

    # Same weights and inputs on both devices, the layer has to compute the same thing.
    def layer_output(make_layer, inputs, device_name, weights=None):
        with tf.device(device_name):
            model = keras.Sequential([keras.Input(batch_shape=inputs.shape), make_layer()])
            if weights is not None:
                model.set_weights(weights)
            return model(inputs, training=False), model.get_weights()

    def check_layer(name, make_layer, inputs):
        try:
            expected, weights = layer_output(make_layer, inputs, "/CPU:0")
            actual, _ = layer_output(make_layer, inputs, device, weights)
            worst = np.max(np.abs(actual.numpy() - expected.numpy())) / max(np.max(np.abs(expected.numpy())), 1e-12)
            on_device = device.strip("/").split(":")[0] in actual.device
            record(f"keras {name}", on_device and bool(worst <= 1e-3),
                   f"device={actual.device.split('/')[-1]} rel_err={worst:.2e}")
        except Exception as e:
            record(f"keras {name}", False, f"{type(e).__name__}: {str(e)[:500]}")

    seq, img, img3d = rand(8, 20, 16), rand(8, 32, 32, 3), rand(4, 8, 16, 16, 2)
    tokens = tf.constant(rng.integers(0, 100, (8, 20)), dtype=tf.int32)

    check_layer("Dense", lambda: keras.layers.Dense(64, activation="relu"), seq)
    check_layer("Conv2D", lambda: keras.layers.Conv2D(16, 3, padding="same", activation="relu"), img)
    check_layer("Conv3D", lambda: keras.layers.Conv3D(4, 3, padding="same"), img3d)
    check_layer("DepthwiseConv2D", lambda: keras.layers.DepthwiseConv2D(3, padding="same"), img)
    check_layer("Conv2DTranspose", lambda: keras.layers.Conv2DTranspose(8, 3, strides=2, padding="same"), img)
    check_layer("MaxPooling2D", lambda: keras.layers.MaxPooling2D(), img)
    check_layer("BatchNormalization", lambda: keras.layers.BatchNormalization(), img)
    check_layer("LayerNormalization", lambda: keras.layers.LayerNormalization(), seq)
    check_layer("Embedding", lambda: keras.layers.Embedding(100, 16), tokens)
    check_layer("LSTM", lambda: keras.layers.LSTM(16, return_sequences=True), seq)
    check_layer("GRU", lambda: keras.layers.GRU(16, return_sequences=True), seq)

    class SelfAttention(keras.layers.Layer):
        def __init__(self):
            super().__init__()
            self.attention = keras.layers.MultiHeadAttention(num_heads=2, key_dim=8)

        def call(self, x):
            return self.attention(x, x)

    check_layer("MultiHeadAttention", SelfAttention, seq)

    def check_fit(name, jit_compile):
        try:
            keras.utils.set_random_seed(0)
            x = rng.standard_normal((512, 32, 32, 3)).astype(np.float32)
            y = (x.mean(axis=(1, 2, 3)) > 0).astype(np.int32)
            with tf.device(device):
                model = keras.Sequential([
                    keras.Input((32, 32, 3)),
                    keras.layers.Conv2D(8, 3, activation="relu"),
                    keras.layers.BatchNormalization(),
                    keras.layers.GlobalAveragePooling2D(),
                    keras.layers.Dense(32, activation="relu"),
                    keras.layers.Dropout(0.1),
                    keras.layers.Dense(2),
                ])
                model.compile(optimizer=keras.optimizers.Adam(1e-2), jit_compile=jit_compile,
                              loss=keras.losses.SparseCategoricalCrossentropy(from_logits=True))
                losses = model.fit(x, y, batch_size=64, epochs=8, verbose=0).history["loss"]
            record(name, bool(np.isfinite(losses).all() and losses[-1] < losses[0]),
                   f"loss {losses[0]:.4f} -> {losses[-1]:.4f}")
        except Exception as e:
            record(name, False, f"{type(e).__name__}: {str(e)[:500]}")

    check_fit("keras fit (graph)", False)
    check_fit("keras fit (XLA)", True)

    failed = [name for name, ok in results if not ok]
    print(f"worker: {len(results) - len(failed)}/{len(results)} passed", flush=True)
    sys.exit(1 if failed else 0)


############################### PTX checks (parent) ###############################


def gpu_architectures():
    """Map every GPU's compute capability to its ptxas name, 12.0 -> sm_120."""
    if not shutil.which("nvidia-smi"):
        return []
    out = run_cmd("nvidia-smi", "--query-gpu=name,driver_version,compute_cap", "--format=csv,noheader")
    print(out.stdout.strip())
    return sorted({"sm_" + line.split(",")[-1].strip().replace(".", "") for line in out.stdout.splitlines()})


def find_ptxas():
    return shutil.which("ptxas") or next(
        (p for p in ["/usr/local/cuda/bin/ptxas"] if os.access(p, os.X_OK)), None)


def check_ptx(dump_dir, archs, ptxas):
    ptx_files = sorted(Path(dump_dir).rglob("*.ptx"))
    if not ptx_files:
        print("XLA did not dump PTX, skipping the direct ptxas check")
        return

    texts = [p.read_text(errors="replace") for p in ptx_files]
    targets = {t.strip() for text in texts for t in re.findall(r"^\s*\.target\s+(.+)$", text, re.M)}
    versions = {v for text in texts for v in re.findall(r"^\s*\.version\s+(\S+)", text, re.M)}
    # opcodes with type suffixes, e.g. fma.rn.f32. Listed so a problem can be matched to one.
    opcodes = {o for text in texts for o in re.findall(r"^\s*(?:@!?%\w+\s+)?([a-z][a-z0-9]*(?:\.[a-z0-9]+)*)\s", text, re.M)}
    print(f"PTX .target {sorted(targets)}, .version {sorted(versions)}, {len(opcodes)} distinct instructions")
    print("PTX instructions: " + " ".join(sorted(opcodes)))

    print(run_cmd(ptxas, "--version").stdout.strip())
    for arch in archs:
        failures = []
        with tempfile.TemporaryDirectory() as out_dir:
            for path in ptx_files:
                result = run_cmd(ptxas, str(path), "-o", f"{out_dir}/out.cubin", f"-arch={arch}", "-m64")
                if result.returncode != 0:
                    failures.append(f"{path.name}: {(result.stderr or result.stdout).strip()[:500]}")
        record(f"ptxas accepts all PTX for {arch}", not failures, f"{len(failures)}/{len(ptx_files)} rejected")
        for failure in failures[:10]:
            print("   ", failure)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--allow-cpu", action="store_true", help="dry run on CPU, skips all GPU and PTX checks")
    parser.add_argument("--expect-arch", help="fail unless every GPU has this architecture, e.g. sm_103")
    parser.add_argument("--worker", metavar="DEVICE", help=argparse.SUPPRESS)
    args = parser.parse_args()

    if args.worker:
        worker(args.worker)
        return

    archs = gpu_architectures()
    ptxas = find_ptxas()
    gpu_run = not args.allow_cpu
    if gpu_run:
        record("nvidia-smi reports a GPU", bool(archs), archs or "start the container with GPU access")
        record("ptxas is available", bool(ptxas), ptxas or "not on PATH, XLA cannot compile PTX")
        if args.expect_arch:
            record(f"all GPUs are {args.expect_arch}", archs == [args.expect_arch], archs)

    with tempfile.TemporaryDirectory() as dump_dir:
        env = dict(os.environ)
        env["XLA_FLAGS"] = f"{env.get('XLA_FLAGS', '')} --xla_dump_to={dump_dir}".strip()
        env["CUDA_CACHE_DISABLE"] = "1"  # a cached JIT result would hide a PTX problem
        env.setdefault("KERAS_BACKEND", "tensorflow")
        device = "/GPU:0" if gpu_run else "/CPU:0"

        # Worker runs in a child so the flags apply before import and a crash is reported.
        process = subprocess.Popen([sys.executable, __file__, "--worker", device], env=env, text=True,
                                   errors="replace", stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        log = []
        worker_results = []
        for line in process.stdout:
            sys.stdout.write(line)
            log.append(line)
            match = re.match(r"\[(PASS|FAIL)\] (.*)", line)
            if match:
                worker_results.append((match.group(2), match.group(1) == "PASS"))
        code = process.wait()
        results.extend(worker_results)
        record("worker finished cleanly", code == 0 or (code == 1 and worker_results), f"exit code {code}")

        hits = [line.strip() for line in log if any(re.search(p, line) for p in BAD_LOG_PATTERNS)]
        record("no PTX or GPU runtime errors in log", not (gpu_run and hits), f"{len(hits)} matching lines")
        for hit in hits[:10]:
            print("   ", hit[:300])

        if gpu_run:
            record("XLA compiled for the GPU", any("initialized for platform CUDA" in line for line in log))
        if gpu_run and archs and ptxas:
            check_ptx(dump_dir, archs, ptxas)

    failed = [name for name, ok in results if not ok]
    print(f"\n{len(results) - len(failed)}/{len(results)} checks passed")
    for name in failed:
        print(f"  FAILED: {name}")
    if not gpu_run:
        print("CPU dry run: the GPU and PTX were NOT tested.")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
